#!/usr/bin/env python3
"""MV-716: put new sprites into the committed atlas without a full regeneration.

    python3 tools/atlas_insert.py room_rear_gunner fx_room_gunner_flash_0 ...

A full `python3 tools/generate_pixel_art.py` rewrites every generated file (backgrounds, events ...) and does not
reproduce the committed pixels byte for byte, so a small art PR would ship hundreds of unrelated changes. This script
builds only the named regions with the same generator functions (tools/art/*.py, registered through common.add), finds
a free spot in the committed atlas.png (1 px padding, never touching an existing region) and writes the pixels + the
new keys. A region that already exists is redrawn in place when its size is unchanged. The next full regeneration packs
everything again from scratch, so the generator functions stay the source of truth.
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
from PIL import Image
from art import common, rooms

ATLAS = os.path.join(common.OUT_ATLAS, "atlas.png")
JSON = os.path.join(common.OUT_ATLAS, "atlas.json")


def build(names):
    common.atlas_items.clear()
    rooms.gen_rooms_x()
    out = {}
    for n in names:
        if n not in common.atlas_items:
            sys.exit("not generated by gen_rooms_x: " + n)
        out[n] = common.atlas_items[n]
    return out


def main(names):
    items = build(names)
    sheet = Image.open(ATLAS).convert("RGBA")
    regions = json.load(open(JSON))
    W, H = sheet.size
    occ = np.zeros((H, W), bool)
    for x, y, w, h in regions.values():
        occ[max(0, y - 1):y + h + 1, max(0, x - 1):x + w + 1] = True
    for n, im in sorted(items.items(), key=lambda kv: -kv[1].height * kv[1].width):
        if n in regions and tuple(regions[n][2:]) == im.size:
            x, y = regions[n][:2]
        else:
            regions.pop(n, None)
            spot = None
            for y in range(0, H - im.height):
                free = ~occ[y:y + im.height].any(0)
                run = 0
                for x in range(W):
                    run = run + 1 if free[x] else 0
                    if run >= im.width:
                        spot = (x - im.width + 1, y)
                        break
                if spot:
                    break
            if spot is None:
                sys.exit("no free space for " + n)
            x, y = spot
        sheet.paste((0, 0, 0, 0), (x, y, x + im.width, y + im.height))
        sheet.alpha_composite(im, (x, y))
        regions[n] = [x, y, im.width, im.height]
        occ[max(0, y - 1):y + im.height + 1, max(0, x - 1):x + im.width + 1] = True
        print(n, regions[n])
    sheet.save(ATLAS, optimize=True)
    with open(JSON, "w") as f:
        json.dump({k: list(v) for k, v in sorted(regions.items())}, f, indent=0)


if __name__ == "__main__":
    main(sys.argv[1:])
